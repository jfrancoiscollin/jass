def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _normalize_source(raw: bytes) -> bytes:
    normalized = raw.replace(b"\r\n", b"\n")
    if b"\r" in normalized:
        raise ValueError("base source contains unsupported bare CR bytes")
    try:
        normalized.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ValueError("base source is not UTF-8") from exc
    return normalized


def replace_exact(text: str, old: str, new: str, count: int = 1) -> str:
    actual = text.count(old)
    if actual != count:
        raise ValueError(f"expected {count} occurrences of {old!r}, got {actual}")
    return text.replace(old, new)


def render(source: str) -> str:
    normalized = source.replace("\r\n", "\n")
    if "\r" in normalized:
        raise ValueError("base source contains unsupported bare CR")
    digest = _sha256(normalized.encode("utf-8"))
    if digest != BASE_SOURCE_NORMALIZED_SHA256:
        raise ValueError(
            "unexpected normalized base source SHA256: "
            f"expected {BASE_SOURCE_NORMALIZED_SHA256}, got {digest}"
        )

    out = normalized
    for old, new in (
        (COUNTERS_OLD, COUNTERS_NEW),
        (ENV_HELPER_ANCHOR, ENV_HELPER_REPLACEMENT),
        (SEARCH_SIG_OLD, SEARCH_SIG_NEW),
        (SEARCH_BODY_OLD, SEARCH_BODY_NEW),
        (REPORT_SIG_OLD, REPORT_SIG_NEW),
        (REPORT_FIELDS_OLD, REPORT_FIELDS_NEW),
        (USAGE_OLD, USAGE_NEW),
        (ARGS_OLD, ARGS_NEW),
        (INVALID_OLD, INVALID_NEW),
        (SEARCHES_OLD, SEARCHES_NEW),
        (TB_CAP_OLD, TB_CAP_NEW),
        (REPORT_CALL_OLD, REPORT_CALL_NEW),
    ):
        out = replace_exact(out, old, new)

    # Remove the sole long-lived Engine after inserting the local constructor.
    out = replace_exact(out, ENGINE_DECL, "")

    if out.count("Engine engine(tt_mb);") != 1:
        raise ValueError("rendered source must contain exactly one local Engine constructor")
    if out.count(CALL_OLD) != 0 or out.count(CALL_NEW) != 3:
        raise ValueError("rendered source does not contain exactly three fresh searches")
    for token in (
        "constexpr std::uint64_t CHEAP_BUDGET = 5'000;",
        "constexpr std::uint64_t SCREEN_BUDGET = 50'000;",
        "constexpr std::uint64_t TEACHER_BUDGET = 200'000;",
        "NodeLimitMode::Exact",
        "q5k_parent",
        "q50_parent",
        "q200_parent",
    ):
        if token not in out:
            raise ValueError(f"rendered source lost frozen teacher token {token!r}")
    return PREFIX + out + SUFFIX


