def validate_shard_report(report: Mapping[str, Any]) -> None:
    keys = frozenset(report)
    if keys != SHARD_REPORT_KEYS:
        raise ValueError(
            f"shard report keys differ: missing={sorted(SHARD_REPORT_KEYS - keys)}, "
            f"extra={sorted(keys - SHARD_REPORT_KEYS)}"
        )
    expected = {
        "schema": SHARD_SCHEMA,
        "book_enabled": False,
        "threads_per_search": 1,
        "fresh_tt_each_search": True,
        "fresh_engine_each_search": True,
        "jass_prefixed_environment_count": 0,
        "egdb_configuration_source": "explicit_positional_arguments",
        "egdb_required_available": True,
        "egdb_cache_mb": REQUIRED_EGDB_CACHE_MB,
        "node_limit_mode": "exact",
        "cheap_budget_nodes": BUDGETS[0],
        "screen_budget_nodes": BUDGETS[1],
        "teacher_budget_nodes": BUDGETS[2],
        "teacher_scores_produced": True,
        "stable_pairs_selected": False,
        "fits": 0,
        "strength_games": 0,
        "promotion_authorized": False,
    }
    for key, value in expected.items():
        if report.get(key) != value or type(report.get(key)) is not type(value):
            raise ValueError(f"unexpected {key}: {report.get(key)!r}")

    input_parents = _require_int(report, "input_parents", SELECTED_PARENTS, SELECTED_PARENTS)
    shard = _require_int(report, "shard", 0, SHARD_COUNT - 1)
    nshards = _require_int(report, "nshards", SHARD_COUNT, SHARD_COUNT)
    _require_int(report, "tt_mb", 1)
    _require_int(report, "egdb_max_pieces", 1, 40)
    if shard >= nshards:
        raise ValueError("shard must be smaller than nshards")
    if _require_int(report, "source_rows") != input_parents:
        raise ValueError("source_rows must equal input_parents")
    expected_processed = len(range(shard, input_parents, nshards))
    if _require_int(report, "processed_parent_rows") != expected_processed:
        raise ValueError("processed_parent_rows disagrees with modulo sharding")
    if _require_int(report, "invalid_rows") != 0:
        raise ValueError("invalid selected-parent rows are forbidden")
    for key in SUM_FIELDS:
        _require_int(report, key)

    emitted = report["emitted_siblings"]
    processed = report["processed_parent_rows"]
    if not 2 * processed <= emitted <= 16 * processed:
        raise ValueError("emitted_siblings outside frozen 2..16 per-parent support")
    if report["rule_terminal_children"] + report["exact_tb_children"] > emitted:
        raise ValueError("exact child counters exceed emitted siblings")
    for key in ("cheap_searches", "screen_searches", "teacher_searches"):
        if report[key] != emitted:
            raise ValueError(f"{key} must equal emitted_siblings")
    if report["engine_constructions"] != 3 * emitted:
        raise ValueError("engine_constructions must equal 3*emitted_siblings")
    for key, budget in (("cheap_nodes", BUDGETS[0]), ("screen_nodes", BUDGETS[1]),
                        ("teacher_nodes", BUDGETS[2])):
        if report[key] > emitted * budget:
            raise ValueError(f"{key} exceeds its exact-node cap")


def merge_reports(reports: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    if len(reports) != SHARD_COUNT:
        raise ValueError(f"exactly {SHARD_COUNT} shard reports are required")
    checked = [dict(report) for report in reports]
    for report in checked:
        validate_shard_report(report)
    nshards = checked[0]["nshards"]
    if len(checked) != nshards:
        raise ValueError("report count must equal nshards")
    by_shard = {report["shard"]: report for report in checked}
    if len(by_shard) != nshards or set(by_shard) != set(range(nshards)):
        raise ValueError("shards must be unique and exhaustive 0..nshards-1")
    ordered = [by_shard[i] for i in range(nshards)]
    invariant_keys = (
        "input_parents", "nshards", "book_enabled", "threads_per_search",
        "fresh_tt_each_search", "fresh_engine_each_search",
        "jass_prefixed_environment_count", "egdb_configuration_source",
        "egdb_required_available", "egdb_cache_mb", "node_limit_mode",
        "cheap_budget_nodes", "screen_budget_nodes", "teacher_budget_nodes",
        "tt_mb", "egdb_max_pieces", "teacher_scores_produced",
        "stable_pairs_selected", "fits", "strength_games", "promotion_authorized",
    )
    for key in invariant_keys:
        if any(report[key] != ordered[0][key] for report in ordered[1:]):
            raise ValueError(f"shard invariant differs for {key}")

    aggregate: dict[str, Any] = {
        "schema": MERGED_SCHEMA,
        "nshards": nshards,
        "input_parents": ordered[0]["input_parents"],
        "book_enabled": False,
        "threads_per_search": 1,
        "fresh_tt_each_search": True,
        "fresh_engine_each_search": True,
        "jass_prefixed_environment_count": 0,
        "egdb_configuration_source": "explicit_positional_arguments",
        "egdb_required_available": True,
        "egdb_cache_mb": REQUIRED_EGDB_CACHE_MB,
        "node_limit_mode": "exact",
        "budgets_nodes": list(BUDGETS),
        "tt_mb": ordered[0]["tt_mb"],
        "egdb_max_pieces": ordered[0]["egdb_max_pieces"],
        "teacher_scores_produced": True,
        "stable_pairs_selected": False,
        "fits": 0,
        "strength_games": 0,
        "promotion_authorized": False,
        "shards": ordered,
    }
    for key in SUM_FIELDS:
        value = sum(report[key] for report in ordered)
        if value > UINT64_MAX:
            raise ValueError(f"merged {key} exceeds uint64")
        aggregate[key] = value
    emitted = aggregate["emitted_siblings"]
    if aggregate["processed_parent_rows"] != aggregate["input_parents"]:
        raise ValueError("merged processed parents must equal input parents")
    if aggregate["cheap_searches"] != emitted or aggregate["screen_searches"] != emitted \
            or aggregate["teacher_searches"] != emitted:
        raise ValueError("merged per-budget searches must equal emitted siblings")
    if aggregate["engine_constructions"] != 3 * emitted:
        raise ValueError("merged engine constructions must equal 3*emitted siblings")
    return aggregate


def load_and_merge_reports(paths: Iterable[Path]) -> dict[str, Any]:
    reports: list[Mapping[str, Any]] = []
    for path in paths:
        value = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(value, dict):
            raise ValueError(f"report is not a JSON object: {path}")
        reports.append(value)
    return merge_reports(reports)


def _path_key(path: Path) -> str:
    return os.path.normcase(os.path.normpath(str(path.resolve(strict=False)))).casefold()


def _require_distinct_paths(paths: Sequence[Path]) -> None:
    keys = [_path_key(path) for path in paths]
    if len(set(keys)) != len(keys):
        raise ValueError("input/output paths must be pairwise distinct")


def _json_bytes(value: Mapping[str, Any]) -> bytes:
    return (json.dumps(value, sort_keys=True, ensure_ascii=True, indent=2) + "\n").encode("ascii")


def _publish_files(
    values: Mapping[Path, bytes], *, protected_inputs: Sequence[Path] = ()
) -> None:
    outputs = list(values)
    temporaries = [Path(str(path) + ".tmp") for path in outputs]
    all_paths = [*protected_inputs, *outputs, *temporaries]
    keys = [_path_key(path) for path in all_paths]
    if len(set(keys)) != len(keys):
        raise ValueError("input/output/temporary paths must be pairwise distinct")
    if any(path.exists() for path in [*outputs, *temporaries]):
        raise ValueError("refusing existing output or temporary path")
    published: list[Path] = []
    try:
        for path, temporary in zip(outputs, temporaries):
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary.write_bytes(values[path])
            if temporary.read_bytes() != values[path]:
                raise ValueError(f"temporary output verification failed: {path}")
        for path, temporary in zip(outputs, temporaries):
            os.replace(temporary, path)
            published.append(path)
        for path in outputs:
            if path.read_bytes() != values[path]:
                raise ValueError(f"published output verification failed: {path}")
    except Exception:
        for path in [*temporaries, *published]:
            path.unlink(missing_ok=True)
        raise


def _write_json(
    path: Path, value: Mapping[str, Any], *, protected_inputs: Sequence[Path] = ()
) -> None:
    _publish_files({path: _json_bytes(value)}, protected_inputs=protected_inputs)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    render_cmd = sub.add_parser("render", help="render the pinned B2 teacher source")
    render_cmd.add_argument("--source", type=Path, default=Path("src/deep_sibling_teacher.cpp"))
    render_cmd.add_argument("--output", type=Path, required=True)
    render_cmd.add_argument("--receipt", type=Path, required=True)
    merge_cmd = sub.add_parser("merge-reports", help="strictly validate and merge shard receipts")
    merge_cmd.add_argument("--report", type=Path, action="append", required=True)
    merge_cmd.add_argument("--output", type=Path, required=True)
    verify_cmd = sub.add_parser(
        "verify-selection", help="authenticate sealed selected parents before teacher search"
    )
    verify_cmd.add_argument("--parents-jnnw", type=Path, required=True)
    verify_cmd.add_argument("--selection-report", type=Path, required=True)
    verify_cmd.add_argument("--expected-selection-report-sha256", required=True)
    verify_cmd.add_argument("--receipt", type=Path, required=True)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    if args.command == "render":
        render_file(args.source, args.output, args.receipt)
    elif args.command == "merge-reports":
        _write_json(
            args.output,
            load_and_merge_reports(args.report),
            protected_inputs=args.report,
        )
    else:
        receipt = verify_selection_input(
            args.parents_jnnw,
            args.selection_report,
            args.expected_selection_report_sha256,
        )
        _write_json(
            args.receipt,
            receipt,
            protected_inputs=(args.parents_jnnw, args.selection_report),
        )
    return 0


